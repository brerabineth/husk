#!/usr/bin/env python3
"""generate packed_blob.h — deterministic 32 KiB random bytes for the
packed fixture. fixed seed, reproducible across builds."""
import random

SEED = 0x4517
LEN = 32 * 1024

rng = random.Random(SEED)
data = bytes(rng.getrandbits(8) for _ in range(LEN))

lines = []
for i in range(0, LEN, 16):
    chunk = data[i:i+16]
    lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")

body = "\n".join(lines)

hdr = f"""/* packed_blob.h — generated by tools/gen_blob.py. do not edit. */
#ifndef PACKED_BLOB_H
#define PACKED_BLOB_H

#include <stddef.h>

#define PACKED_BLOB_LEN {LEN}

static const unsigned char packed_blob_data[{LEN}] = {{
{body}
}};

#define PACKED_BLOB_DATA packed_blob_data[i], packed_blob_data[i+1]

#endif /* PACKED_BLOB_H */
"""

# PACKED_BLOB_DATA trick above is wrong for array init; emit a real init instead
hdr = f"""/* packed_blob.h — generated by tools/gen_blob.py. do not edit. */
#ifndef PACKED_BLOB_H
#define PACKED_BLOB_H

#define PACKED_BLOB_LEN {LEN}

static const unsigned char husk_blob_data[{LEN}] = {{
{body}
}};

#endif /* PACKED_BLOB_H */
"""

open(__import__("os").path.join(
    __import__("os").path.dirname(__file__),
    "..", "fixtures", "src", "packed_blob.h"), "w").write(hdr)
print(f"packed_blob.h written ({LEN} bytes, seed {SEED})")
